/**
 * ================================================================
 *  CRE Workflow: generate-finale
 *  CHAINLINK SERVICE: CRE / Keystone (Decentralized Oracle Network)
 * ================================================================
 *
 *  PURPOSE:
 *    Listens for the on-chain `CarmenCaptured` event emitted when a
 *    player captures Carmen Sandiego. The workflow generates a unique
 *    victory narrative, builds ERC-721 metadata with an SVG trophy
 *    image, and sets the token URI on the MissionNFT contract via
 *    the GameMasterProxy (ACTION_SET_TOKEN_URI = 6).
 *
 *  CHAINLINK CRE INTEGRATION:
 *    This is the "reward minter" workflow — it demonstrates CRE's ability
 *    to generate complex, dynamic NFT content (SVG images + JSON metadata)
 *    entirely within the Decentralized Oracle Network. No centralized
 *    server or IPFS gateway is needed.
 *
 *    WHY DECENTRALIZED:
 *    - Trophy NFTs are minted with content generated by the DON, not a
 *      centralized API. This prevents the game developer from minting
 *      fake trophies or manipulating reward tiers.
 *    - The SVG image and metadata are deterministic (based on on-chain
 *      mission data), so all DON nodes produce identical output.
 *    - The ERC-721 token URI is set via a Keystone-signed report,
 *      meaning only the authorized CRE workflow can set trophy metadata.
 *    - Fully on-chain data URIs (data:application/json;base64,...) mean
 *      the NFT is self-contained — no IPFS, no external dependencies.
 *
 *  DATA FLOW:
 *    1. mission-start workflow sends ACTION_RESOLVE_CAPTURE when
 *       the player finds Carmen with enough clues
 *    2. GameMaster.resolveCapture() mints an ERC-721 trophy NFT
 *       and emits CarmenCaptured(missionId, player, blocksUsed, reward)
 *    3. CRE DON detects CarmenCaptured via LogTrigger capability
 *    4. DON nodes execute this WASM workflow:
 *       a. Read mission data (clues, evidence, salt, cities)
 *       b. Determine reward tier (Gold/Silver/Bronze/Copper)
 *       c. Brute-force salt to identify the capture city name
 *       d. Generate victory narrative (enriched template / AI)
 *       e. Build dynamic SVG trophy image with mission stats
 *       f. Encode ERC-721 metadata JSON as base64 data URI
 *    5. DON consensus produces a signed Keystone report
 *    6. Report delivered: ACTION_SET_TOKEN_URI -> GameMasterProxy
 *    7. Proxy sets the token URI on MissionNFT.sol
 *
 *  CHAINLINK SERVICES USED:
 *    - CRE/Keystone: WASM execution, LogTrigger, consensus, signed reports
 *    - EVMClient: Reads mission state, evidence count, salt from Sepolia
 *    - writeReport: On-chain delivery via Keystone Forwarder
 *    - VRF v2.5: The reward amount is derived from VRF-seeded block count
 *
 *  AI GENERATION:
 *    The workflow includes a full OpenAI integration (generateAIFinale)
 *    for unique personalized endings. CRE WASM currently doesn't support
 *    async/await, so the AI path uses buildEnrichedFinale as fallback.
 *    When CRE v2 supports async handlers, enable with a one-line change.
 *
 *  NFT METADATA:
 *    Uses on-chain data URI (data:application/json;base64,...) to avoid
 *    IPFS dependency. The SVG trophy image is also embedded as a data URI.
 *    This approach is fully synchronous and works within CRE WASM.
 *
 *  CONFIG:
 *    - chainSelectorName, gameMasterAddress, proxyAddress, gasLimit
 *    - openaiApiKey: OpenAI API key (optional — empty = use fallback)
 *    - openaiModel: model to use (e.g. "gpt-4o-mini")
 *
 *  IMPORTANT CONSTRAINTS:
 *    - Handler must be synchronous (async AI calls are behind TODO)
 *    - .result() for blocking EVM reads
 * ================================================================
 */

